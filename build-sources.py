# Run after editing any project page:  python3 build-sources.py
import json,glob,os
r=os.path.dirname(os.path.abspath(__file__))
skip={'index.html'}
d={os.path.basename(f)[:-5]:open(f,encoding='utf-8').read() for f in sorted(glob.glob(r+'/*.html')) if os.path.basename(f) not in skip}
open(r+'/sources.js','w',encoding='utf-8').write('/* generated by build-sources.py */\nwindow.SRC='+json.dumps(d,indent=1)+';')
